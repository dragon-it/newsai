-- ============================================================
-- NewsAI 데이터베이스 설계도
-- ============================================================
-- Supabase 프로젝트는 처음 만들면 비어 있는 창고와 같습니다.
-- 이 파일은 그 창고 안에 다음 두 개의 보관함을 만듭니다.
--
--   1. reports  : 날짜별 전체 리포트를 보관하는 표
--   2. articles : 각 리포트에 포함된 개별 기사를 보관하는 표
--
-- SQL에서 표를 "테이블(table)"이라고 부릅니다.
-- 테이블의 세로 항목은 "컬럼(column)", 실제 데이터 한 줄은 "행(row)"입니다.
--
-- 이 파일에는 테이블을 통째로 제거하는 DROP TABLE 명령이 없습니다.
-- 새 Supabase 프로젝트에서 처음 실행하면 빈 테이블과 저장 함수를 만듭니다.


-- ============================================================
-- 1. 날짜별 리포트를 저장할 reports 테이블
-- ============================================================
-- "if not exists"는 reports 테이블이 이미 있다면 다시 만들지 말라는 뜻입니다.
create table if not exists public.reports (
  -- 각 리포트의 고유 번호입니다.
  -- 1, 2, 3처럼 PostgreSQL이 자동으로 번호를 붙입니다.
  id bigint generated by default as identity primary key,

  -- 리포트 날짜입니다.
  -- not null: 날짜를 반드시 넣어야 합니다.
  -- unique: 같은 날짜의 리포트를 두 개 만들 수 없습니다.
  report_date date not null unique,

  -- 뉴스 수집과 분석이 실제로 완료된 시각입니다.
  -- timestamptz는 시간대 정보까지 포함하는 날짜·시간 형식입니다.
  last_updated timestamptz not null,

  -- 그날 수집한 뉴스 전체를 요약한 긴 글입니다.
  summary text not null,

  -- 대시보드에 표시하는 그날의 종합 점수입니다.
  -- numeric(5, 2)는 소수점 아래 두 자리까지 저장할 수 있는 숫자입니다.
  summary_score numeric(5, 2) not null,

  -- 그날 AI 변화 속도를 나타내는 값입니다.
  daily_velocity numeric(6, 2) not null,

  -- daily_velocity가 왜 그 값으로 계산되었는지 설명하는 글입니다.
  velocity_reason text not null,

  -- 이전 날짜부터 계속 누적해서 계산한 위험 점수입니다.
  cumulative_risk_score numeric(5, 2) not null,

  -- 대시보드에서 사용하는 직업 위험 점수입니다.
  job_risk_score numeric(5, 2) not null,

  -- 위험 점수를 올리거나 내린 사건들의 목록입니다.
  -- 프론트엔드의 JSON 배열과 비슷한 데이터를 저장하기 때문에 jsonb를 사용합니다.
  -- 값이 전달되지 않으면 빈 배열([])로 저장합니다.
  risk_score_breakdown jsonb not null default '[]'::jsonb,

  -- 과거에 reports/report-날짜.md 파일로 저장하던 Markdown 전체 내용입니다.
  markdown_content text not null,

  -- 이 리포트 행이 DB에 처음 만들어진 시각입니다.
  -- 값을 따로 주지 않으면 now()가 현재 시각을 자동으로 넣습니다.
  created_at timestamptz not null default now(),

  -- 이 리포트가 마지막으로 수정된 시각입니다.
  updated_at timestamptz not null default now()
);


-- ============================================================
-- 2. 개별 기사를 저장할 articles 테이블
-- ============================================================
create table if not exists public.articles (
  -- 각 기사의 고유 번호입니다. PostgreSQL이 자동으로 생성합니다.
  id bigint generated by default as identity primary key,

  -- 이 기사가 어떤 리포트에 포함되는지 나타내는 번호입니다.
  -- reports.id를 가리키기 때문에 두 테이블이 서로 연결됩니다.
  --
  -- 예: report_id가 10이면 reports 테이블의 id 10번 리포트 소속입니다.
  --
  -- on delete cascade는 나중에 리포트를 실제로 삭제할 경우,
  -- 그 리포트에 속한 기사도 함께 정리하라는 규칙입니다.
  -- 이 스키마 파일을 실행하는 것만으로 데이터가 삭제되지는 않습니다.
  report_id bigint not null references public.reports(id) on delete cascade,

  -- 한 리포트 안에서 기사를 화면에 보여줄 순서입니다.
  -- 0이면 첫 번째 기사, 1이면 두 번째 기사입니다.
  sort_order integer not null,

  -- 기사 제목입니다.
  title text not null,

  -- 기사 원문 주소입니다.
  link text not null,

  -- 원본 뉴스가 제공한 기사 발행 시각입니다.
  -- 원본 RSS의 날짜 문자열을 그대로 보관하기 위해 text를 사용합니다.
  published_at text,

  -- AI가 생성한 개별 기사 요약입니다.
  summary text not null,

  -- 기사 중요도입니다.
  importance smallint not null,

  -- 해당 기사가 AI 발전에 미치는 영향도입니다.
  ai_impact smallint not null,

  -- 해당 기사가 보여주는 업무 자동화 가능성입니다.
  automation_potential smallint not null,

  -- 해당 기사가 투자에 미칠 수 있는 영향도입니다.
  investment_impact smallint not null,

  -- 이 기사 행이 DB에 처음 저장된 시각입니다.
  created_at timestamptz not null default now(),

  -- 하나의 리포트 안에서 같은 표시 순서를 두 번 사용할 수 없게 합니다.
  -- 예를 들어 한 리포트에 '첫 번째 기사'가 두 개 생기는 것을 막습니다.
  unique (report_id, sort_order)
);


-- ============================================================
-- 3. 테이블 보안 설정
-- ============================================================
-- RLS(Row Level Security)는 테이블에 자물쇠를 거는 기능입니다.
-- RLS를 켜면 어떤 사용자가 어떤 행을 읽고 수정할 수 있는지 통제할 수 있습니다.
alter table public.reports enable row level security;
alter table public.articles enable row level security;

-- anon은 로그인하지 않은 일반 방문자 역할입니다.
-- authenticated는 Supabase에 로그인한 일반 사용자 역할입니다.
-- 두 역할이 리포트와 기사를 직접 읽거나 수정하지 못하도록 권한을 회수합니다.
-- revoke는 데이터를 삭제하는 명령이 아니라 "접근 권한"을 없애는 명령입니다.
revoke all on table public.reports from anon, authenticated;
revoke all on table public.articles from anon, authenticated;

-- service_role은 서버에서만 사용하는 관리자 역할입니다.
-- GitHub Actions에 안전하게 저장할 Supabase Secret Key가 이 역할로 접근합니다.
-- 일반 웹 브라우저나 React 코드에는 이 Secret Key를 절대로 넣으면 안 됩니다.
grant all on table public.reports to service_role;
grant all on table public.articles to service_role;

-- 자동 증가 번호(id)를 만들 때 사용하는 내부 번호표(sequence)에
-- service_role이 접근할 수 있도록 허용합니다.
grant usage, select on all sequences in schema public to service_role;


-- ============================================================
-- 4. 하루치 리포트와 기사들을 한 번에 저장하는 DB 함수
-- ============================================================
-- 프론트엔드에서 function을 만드는 것처럼 PostgreSQL 안에도 함수를 만들 수 있습니다.
-- GitHub Actions는 이 함수에 다음 두 값을 전달합니다.
--
--   report   : 전체 요약, 점수, 기사 배열 등이 들어 있는 JSON 객체
--   markdown : Markdown 형식의 전체 리포트 문자열
--
-- create or replace는 같은 함수가 없으면 만들고, 이미 있으면 함수 코드만
-- 최신 내용으로 교체하라는 뜻입니다. reports/articles 데이터는 제거하지 않습니다.
--
-- security definer는 이 함수를 만든 관리자의 권한으로 실행한다는 뜻입니다.
-- 아래에서 일반 사용자의 함수 실행 권한을 제거하고 service_role에만 허용하므로,
-- GitHub Actions만 이 저장 함수를 호출할 수 있습니다.
create or replace function public.save_daily_report(report jsonb, markdown text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  -- 저장하거나 수정한 리포트의 id를 잠시 기억할 변수입니다.
  -- 뒤에서 개별 기사와 리포트를 연결할 때 사용합니다.
  saved_report_id bigint;
begin
  -- ----------------------------------------------------------
  -- 4-1. reports 테이블에 하루치 리포트를 저장합니다.
  -- ----------------------------------------------------------
  insert into public.reports (
    report_date,
    last_updated,
    summary,
    summary_score,
    daily_velocity,
    velocity_reason,
    cumulative_risk_score,
    job_risk_score,
    risk_score_breakdown,
    markdown_content,
    updated_at
  ) values (
    -- JSON 안의 reportDate 문자열을 PostgreSQL 날짜로 변환합니다.
    (report->>'reportDate')::date,

    -- JSON 안의 lastUpdated 문자열을 시간대가 있는 날짜·시간으로 변환합니다.
    (report->>'lastUpdated')::timestamptz,

    -- ->>는 JSON 안의 값을 글자 형태로 꺼내는 PostgreSQL 문법입니다.
    report->>'summary',
    (report->>'summaryScore')::numeric,
    (report->>'dailyVelocity')::numeric,
    report->>'velocityReason',
    (report->>'cumulativeRiskScore')::numeric,
    (report->>'jobRiskScore')::numeric,

    -- 위험 점수 근거가 없으면 빈 JSON 배열을 저장합니다.
    coalesce(report->'riskScoreBreakdown', '[]'::jsonb),

    -- 함수의 두 번째 입력값인 Markdown 전체 내용을 저장합니다.
    markdown,

    -- 현재 시각을 마지막 수정 시각으로 저장합니다.
    now()
  )

  -- 같은 report_date가 이미 있으면 unique 규칙과 충돌합니다.
  -- 이때 새 리포트를 중복 생성하지 않고 기존 날짜의 리포트를 수정합니다.
  -- 따라서 GitHub Actions를 같은 날 여러 번 실행해도 날짜별 리포트는 하나입니다.
  on conflict (report_date) do update set
    last_updated = excluded.last_updated,
    summary = excluded.summary,
    summary_score = excluded.summary_score,
    daily_velocity = excluded.daily_velocity,
    velocity_reason = excluded.velocity_reason,
    cumulative_risk_score = excluded.cumulative_risk_score,
    job_risk_score = excluded.job_risk_score,
    risk_score_breakdown = excluded.risk_score_breakdown,
    markdown_content = excluded.markdown_content,
    updated_at = now()

  -- 방금 생성하거나 수정한 리포트의 id를 saved_report_id에 넣습니다.
  returning id into saved_report_id;

  -- ----------------------------------------------------------
  -- 4-2. 같은 날짜 리포트의 기존 기사 목록을 정리합니다.
  -- ----------------------------------------------------------
  -- 같은 날 파이프라인을 다시 실행하면 새 기사 목록이 만들어집니다.
  -- 기존 기사에 새 기사를 단순 추가하면 중복과 오래된 기사가 섞이므로,
  -- "방금 저장한 그 리포트"에 속한 기사만 지운 뒤 새 목록으로 교체합니다.
  -- 다른 날짜의 기사와 리포트는 건드리지 않습니다.
  --
  -- 이 DELETE 문은 지금 스키마를 등록할 때 실행되지 않습니다.
  -- 나중에 GitHub Actions가 save_daily_report 함수를 호출할 때만 실행됩니다.
  delete from public.articles
  where report_id = saved_report_id;

  -- ----------------------------------------------------------
  -- 4-3. 새 기사 목록을 articles 테이블에 저장합니다.
  -- ----------------------------------------------------------
  insert into public.articles (
    report_id,
    sort_order,
    title,
    link,
    published_at,
    summary,
    importance,
    ai_impact,
    automation_potential,
    investment_impact
  )
  select
    -- 모든 기사를 위에서 저장한 리포트 id와 연결합니다.
    saved_report_id,

    -- JSON 배열의 순번은 1부터 시작하므로 1을 빼서 0부터 저장합니다.
    (item.ordinality - 1)::integer,

    -- 기사 JSON 객체에서 각 값을 꺼내 articles 컬럼에 넣습니다.
    item.value->>'title',
    item.value->>'link',
    item.value->>'pubDate',
    item.value->>'summary',

    -- 각 점수가 없으면 기본값 3을 사용합니다.
    coalesce((item.value->>'importance')::smallint, 3),
    coalesce((item.value->>'aiImpact')::smallint, 3),
    coalesce((item.value->>'automationPotential')::smallint, 3),
    coalesce((item.value->>'investmentImpact')::smallint, 3)

  -- report.news JSON 배열을 기사 하나씩 분리합니다.
  -- with ordinality는 각 기사에 1, 2, 3 순번을 함께 붙여줍니다.
  from jsonb_array_elements(coalesce(report->'news', '[]'::jsonb))
    with ordinality as item(value, ordinality);

  -- 이 함수 안의 모든 작업은 하나의 묶음으로 처리됩니다.
  -- 리포트나 기사 저장 중 하나라도 실패하면 함수 전체가 실패하고,
  -- 중간까지만 저장된 불완전한 데이터가 남지 않습니다.
end;
$$;


-- ============================================================
-- 5. 저장 함수의 실행 권한 설정
-- ============================================================
-- 모든 사람(public), 익명 방문자(anon), 일반 로그인 사용자(authenticated)가
-- save_daily_report 함수를 실행하지 못하도록 권한을 회수합니다.
-- 이 revoke도 데이터 삭제가 아니라 함수 실행 권한을 제거하는 명령입니다.
revoke all on function public.save_daily_report(jsonb, text)
from public, anon, authenticated;

-- GitHub Actions에서 사용하는 서버 관리자 역할만 저장 함수를 실행할 수 있습니다.
grant execute on function public.save_daily_report(jsonb, text)
to service_role;
